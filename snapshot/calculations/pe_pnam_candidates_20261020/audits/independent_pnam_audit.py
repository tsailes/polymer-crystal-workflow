"""Independent geometric and symmetry audit; no refined coordinates or energies.

Run with the project Python environment. All results are printed to stdout.
Positions are deliberately left unwrapped so the image labels of the declared
two infinite chains remain explicit.
"""
from __future__ import annotations

import json
import math
from itertools import product

import gemmi
import numpy as np
import spglib
from ase import Atoms
from ase.data import vdw_radii
from ase.geometry import get_dihedrals
from ase.neighborlist import neighbor_list

CELL = np.diag([7.432, 4.929, 2.545])
CC, CH = 1.54, 1.09
IDENTITY_SHIFT = (0, 0, 0)


def make_pe(theta_deg, center=(0.0, 0.0), phase=0.25):
    h = CELL[2, 2] / 2
    transverse_step = math.sqrt(CC * CC - h * h)
    q = CC / (3 * transverse_step)
    theta = math.radians(theta_deg)
    e = np.array([math.cos(theta), math.sin(theta), 0.0])
    n = np.array([-math.sin(theta), math.cos(theta), 0.0])
    pos, symbols, chain_ids = [], [], []
    block = []
    for carbon, sign in enumerate([1, -1]):
        p = sign * transverse_step / 2 * e
        p[2] = (phase + carbon / 2) * CELL[2, 2]
        block.append(("C", p))
        for hydrogen_sign in [1, -1]:
            d = CH * (sign * q * e + hydrogen_sign * math.sqrt(1-q*q) * n)
            block.append(("H", p+d))
    # The second chain is generated by x+1/2, -y+1/2, z.
    for chain, reflection, offset in [
        (0, np.diag([1, 1, 1]), np.array([center[0], center[1], 0.0]) @ CELL),
        (1, np.diag([1, -1, 1]), np.array([center[0]+0.5, 0.5-center[1], 0.0]) @ CELL),
    ]:
        for symbol, p in block:
            pos.append(reflection @ p + offset)
            symbols.append(symbol)
            chain_ids.append(chain)
    atoms = Atoms(symbols, positions=pos, cell=CELL, pbc=True)
    atoms.set_array("chain_id", np.array(chain_ids, int))
    return atoms


def pnam_residual(atoms):
    positions = atoms.get_scaled_positions(wrap=True)
    numbers = atoms.numbers
    residuals = []
    for operation in gemmi.SpaceGroup("P n a m").operations():
        transformed = np.asarray([operation.apply_to_xyz(x) for x in positions])
        distances = transformed[:, None, :] - positions[None, :, :]
        distances -= np.rint(distances)
        distances = np.linalg.norm(distances @ CELL, axis=2)
        distances[numbers[:, None] != numbers[None, :]] = np.inf
        residuals.append(float(distances.min(axis=1).max()))
    return max(residuals)


def translated_residual(first, second, shift):
    x = first.get_scaled_positions(wrap=True) + np.array(shift)
    y = second.get_scaled_positions(wrap=True)
    delta = x[:, None, :] - y[None, :, :]
    delta -= np.rint(delta)
    distance = np.linalg.norm(delta @ CELL, axis=2)
    distance[first.numbers[:, None] != second.numbers[None, :]] = np.inf
    return float(distance.min(axis=1).max())


def bonded_graph():
    graph = {i: [] for i in range(12)}

    def edge(i, j, shift):
        graph[i].append((j, np.array(shift, int)))
        graph[j].append((i, -np.array(shift, int)))

    for base in (0, 6):
        edge(base, base+3, (0, 0, 0))
        edge(base, base+3, (0, 0, -1))
        for carbon in (base, base+3):
            edge(carbon, carbon+1, (0, 0, 0))
            edge(carbon, carbon+2, (0, 0, 0))
    return graph


def exclusions():
    """Image-resolved 1-2 and 1-3 topology; never inferred from contacts."""
    graph = bonded_graph()
    excluded = {i: set() for i in range(12)}
    for i in range(12):
        for j, shift1 in graph[i]:
            excluded[i].add((j, *map(int, shift1)))
            for k, shift2 in graph[j]:
                excluded[i].add((k, *map(int, shift1+shift2)))
    return excluded


def contact_check(atoms):
    excluded = exclusions()
    chain_ids = atoms.arrays["chain_id"]
    ii, jj, shifts, distances = neighbor_list("ijSd", atoms, 6.0, self_interaction=False)
    min_inter_cc = float("inf")
    min_ratio = float("inf")
    violating_pairs = set()
    minimum_pair = None
    for i, j, shift, distance in zip(ii, jj, shifts, distances):
        same_chain = chain_ids[i] == chain_ids[j] and shift[0] == shift[1] == 0
        if not same_chain and atoms.numbers[i] == atoms.numbers[j] == 6:
            min_inter_cc = min(min_inter_cc, float(distance))
        if (int(j), *map(int, shift)) in excluded[int(i)]:
            continue
        ratio = distance / (vdw_radii[atoms.numbers[i]] + vdw_radii[atoms.numbers[j]])
        if ratio < min_ratio:
            min_ratio = float(ratio)
            minimum_pair = {
                "i_1based": int(i)+1, "j_1based": int(j)+1,
                "shift": shift.tolist(), "distance_A": float(distance),
                "species": atoms[i].symbol + atoms[j].symbol,
                "same_infinite_chain": bool(same_chain),
            }
        if ratio < 0.85 - 1e-10:
            forward = (int(i), int(j), *map(int, shift))
            backward = (int(j), int(i), *map(int, -shift))
            violating_pairs.add(min(forward, backward))
    return {
        "min_interchain_CC_A": min_inter_cc,
        "min_nonbonded_r_over_vdw_sum": min_ratio,
        "minimum_nonbonded_pair": minimum_pair,
        "violating_nonbonded_pairs_per_cell": len(violating_pairs),
        "passes_CC_3p4": min_inter_cc >= 3.4 - 1e-10,
        "passes_vdw_0p85": min_ratio >= 0.85 - 1e-10,
        "passes_both": min_inter_cc >= 3.4-1e-10 and min_ratio >= 0.85-1e-10,
    }


def main():
    hall = spglib.get_spacegroup_type(297)
    operations = [operation.triplet() for operation in gemmi.SpaceGroup("P n a m").operations()]
    database_ops = spglib.get_symmetry_from_database(297)

    def key(rotation, translation):
        return (tuple(np.asarray(rotation, int).flatten()),
                tuple(np.round(np.asarray(translation, float) % 1, 10)))

    gemmi_keys = {key(np.asarray(op.rot) / op.DEN, np.asarray(op.tran) / op.DEN)
                  for op in gemmi.SpaceGroup("P n a m").operations()}
    spglib_keys = {key(rotation, translation) for rotation, translation in
                   zip(database_ops["rotations"], database_ops["translations"])}
    assert gemmi_keys == spglib_keys, "Gemmi and spglib operations differ"
    rows = []
    for angle in range(0, 181, 5):
        atoms = make_pe(angle)
        dataset = spglib.get_symmetry_dataset((CELL, atoms.get_scaled_positions(), atoms.numbers), symprec=1e-6)
        rows.append({
            "angle_deg": angle, "pnam_residual_A": pnam_residual(atoms),
            "detected_number": int(dataset.number), "detected_hall_number": int(dataset.hall_number),
            **contact_check(atoms),
        })
    retained = []
    duplicates = []
    half_translations = list(product([0.0, 0.5], repeat=3))
    for row in rows:
        if not row["passes_both"]:
            continue
        atoms = make_pe(row["angle_deg"])
        match = None
        for previous in retained:
            previous_atoms = make_pe(previous)
            for shift in half_translations:
                residual = translated_residual(atoms, previous_atoms, shift)
                if residual < 1e-7:
                    match = {"angle": row["angle_deg"], "representative_angle": previous,
                             "whole_crystal_translation": list(shift), "residual_A": residual}
                    break
            if match is not None:
                break
        if match:
            duplicates.append(match)
        else:
            retained.append(row["angle_deg"])
    example = make_pe(35)
    carbon_sequence = np.array([example.positions[0], example.positions[3],
                               example.positions[0] + CELL[2], example.positions[3] + CELL[2]])
    vectors = np.diff(carbon_sequence, axis=0)
    torsion = get_dihedrals(vectors[0][None], vectors[1][None], vectors[2][None])[0]
    translation_probes = []
    for center in [(0, 0), (0.5, 0), (0, 0.5), (0.5, 0.5), (0.25, 0.25), (0.1, 0.2)]:
        for phase in [0, 0.125, 0.25, 0.5, 0.75]:
            translation_probes.append({
                "center": list(center), "phase": phase,
                "pnam_residual_A": pnam_residual(make_pe(35, center, phase)),
            })
    print(json.dumps({
        "source": "Chemical geometry plus Gemmi/spglib symmetry operations only; no solved coordinates.",
        "parameters": {"cell_A": CELL.tolist(), "CC_A": CC, "CH_A": CH,
                       "vdw_C_A": float(vdw_radii[6]), "vdw_H_A": float(vdw_radii[1]),
                       "exclude_topological_distance": [1, 2]},
        "hall_database": {"number": hall.number, "hall_number": hall.hall_number,
                          "international": hall.international_short, "hall": hall.hall_symbol},
        "operations": operations,
        "gemmi_spglib_operation_sets_match": gemmi_keys == spglib_keys,
        "angles_inclusive_0_180": rows,
        "passing_angles": [row["angle_deg"] for row in rows if row["passes_both"]],
        "count_passing_inclusive": sum(row["passes_both"] for row in rows),
        "count_passing_excluding_duplicate_180": sum(row["passes_both"] for row in rows[:-1]),
        "unique_passing_angles_mod_half_cell_global_translations": retained,
        "translation_duplicates": duplicates,
        "two_carbon_period_dihedral_deg": float(torsion),
        "two_carbon_torsion_argument": "Consecutive carbons A,B,A+c,B+c lie in the "
            "plane spanned by B-A and c. Equal C-C lengths fix projection c/2. "
            "The valid noncollinear two-carbon pure-translation chain is trans; "
            "gauche values cannot be independently assigned in this repeat.",
        "translation_probes": translation_probes,
    }, indent=2))


if __name__ == "__main__":
    main()
